import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("Materials AI production smoke uses public auth, exam grading, knowledge graph Q&A, and cleanup", async () => {
  const source = await readFile("scripts/smoke-material-ai-production.mjs", "utf8");
  assert.match(source, /FEATURE_MATERIAL_AI.*"true"/);
  assert.match(source, /MATERIAL_AI_EXPECT_LUNA_ENABLED/);
  assert.match(source, /FEATURE_MATERIAL_AI_LUNA/);
  assert.doesNotMatch(source, /MATERIAL_AI_EXPECT_OX_ALPHA_ENABLED|stealth\/ox-alpha/);
  assert.match(source, /OPENROUTER_ZDR_UNAVAILABLE/);
  assert.match(source, /MATERIAL_AI_FAKE_PROVIDER.*"true"/);
  assert.match(source, /ai-capabilities/);
  assert.match(source, /pipeline: "luna_native_file_v1"/);
  assert.match(source, /openai\/gpt-6-luna/);
  assert.match(source, /upstream_provider === "Azure"/);
  assert.match(source, /\/materials\/\$\{source\.material\.id\}\/ai-jobs/);
  assert.match(source, /\/exam-attempts\/\$\{attempt\.id\}\/answers/);
  assert.match(source, /\/exam-attempts\/\$\{attempt\.id\}\/submit/);
  assert.match(source, /kind: "knowledge_graph"/);
  assert.match(source, /knowledge-nodes\/\$\{selectedNode\.id\}\/questions/);
  assert.match(source, /knowledge-graph-layout/);
  assert.match(source, /ai-jobs\/clear-history/);
  assert.match(source, /knowledge_graph_generation/);
  assert.match(source, /knowledge_node_question/);
  assert.match(source, /ai_provider_usage_events/);
  assert.match(source, /material-courses\/\$\{source\.course\.id\}\?aiResults=delete/);
  assert.match(source, /finally \{[\s\S]*await cleanup\(\)/);
  assert.doesNotMatch(source, /console\.log\([^\n]*(serviceKey|access_token|OPENROUTER_API_KEY)/i);
});
